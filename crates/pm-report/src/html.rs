//! Autopsy's HTML report (`HTMLReport`): `report.html` is a frameset with
//! the navigation (`content/nav.html`) and the case summary
//! (`content/summary.html`); each data type is a page in `content/` with
//! its tables, sharing Autopsy's stylesheet (`content/index.css`).

