pub(crate) fn esc(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            c => out.push(c),
        }
    }
    out
}

/// One data type page and its row count (for the navigation).
#[derive(Debug)]
struct Page {
    title: String,
    file: String,
    rows: usize,
}

pub struct HtmlReport {
    dir: PathBuf,
    summary: String,
    pages: Vec<Page>,
    /// The page being written.
    out: Option<std::io::BufWriter<std::fs::File>>,
    rows_in_page: usize,
    error: Option<ReportError>,
}

impl std::fmt::Debug for HtmlReport {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("HtmlReport")
            .field("dir", &self.dir)
            .finish_non_exhaustive()
    }
}

impl HtmlReport {
    pub fn new(dir: &Path, case: &Case, settings: &ReportSettings) -> Self {
        Self {
            dir: dir.to_path_buf(),
            summary: summary_html(case, settings),
            pages: Vec::new(),
            out: None,
            rows_in_page: 0,
            error: None,
        }
    }

    /// `report.html`.
    pub fn index_path(&self) -> PathBuf {
        self.dir.join("report.html")
    }

    fn content(&self) -> PathBuf {
        self.dir.join(SUBDIR)
    }

    fn write_file(&self, name: &str, text: &str) -> Result<(), ReportError> {
        let p = if name == "report.html" {
            self.dir.join(name)
        } else {
            self.content().join(name)
        };
        std::fs::write(&p, text).map_err(io_err(&p))
    }

    fn w(&mut self, text: &str) -> Result<(), ReportError> {
        if let Some(out) = self.out.as_mut() {
            let p = self.dir.clone();
            out.write_all(text.as_bytes()).map_err(io_err(&p))?;
        }
        Ok(())
    }
}

fn page_head(title: &str) -> String {
    format!(
        "<html>\n<head>\n\t<title>{t}</title>\n\t<link rel=\"stylesheet\" type=\"text/css\" href=\"index.css\" />\n<meta http-equiv=\"Content-Type\" content=\"text/html; charset=utf-8\">\n</head>\n<body>\n",
        t = esc(title)
    )
}

fn summary_html(case: &Case, settings: &ReportSettings) -> String {
    let d = case.details();
    let mut s = page_head("Case Summary");
    s.push_str("<div id=\"header\">Report Navigation</div>\n<div id=\"content\">\n");
    let _ = write!(
        s,
        "<h1>{} Forensic Report</h1>\n<p>Generated by postmortem {} on {}.</p>\n",
        esc(&d.name),
        env!("CARGO_PKG_VERSION"),
        esc(&jiff::Zoned::now()
            .strftime("%Y/%m/%d %H:%M:%S %Z")
            .to_string())
    );
    s.push_str("<h2>Case Summary</h2>\n<table>\n");
    for (k, v) in [
        ("Case", d.name.as_str()),
        ("Case Number", d.number.as_str()),
        ("Examiner", d.examiner.name.as_str()),
    ] {
        let _ = writeln!(s, "<tr><td>{k}:</td><td>{}</td></tr>", esc(v));
    }
    let sources = case.db().data_sources().unwrap_or_default();
    let _ = writeln!(
        s,
        "<tr><td>Number of data sources in case:</td><td>{}</td></tr>",
        sources.len()
    );
    s.push_str("</table>\n<h2>Data Sources</h2>\n");
    for ds in sources
        .iter()
        .filter(|d| settings.data_sources.is_empty() || settings.data_sources.contains(&d.id))
    {
        let _ = write!(
            s,
            "<table>\n<tr><td>Name:</td><td>{}</td></tr>\n<tr><td>Time Zone:</td><td>{}</td></tr>\n",
            esc(&ds.name),
            esc(&ds.timezone)
        );
        for p in &ds.paths {
            let _ = writeln!(s, "<tr><td>Path:</td><td>{}</td></tr>", esc(p));
        }
        s.push_str("</table>\n");
    }
    s.push_str("</div>\n</body>\n</html>");
    s
}

impl TableReportModule for HtmlReport {
    fn start_report(&mut self) -> Result<(), ReportError> {
        let content = self.content();
        std::fs::create_dir_all(&content).map_err(io_err(&content))?;
        self.write_file("index.css", CSS)?;
        let summary = std::mem::take(&mut self.summary);
        self.write_file("summary.html", &summary)
    }

    fn end_report(&mut self) -> Result<(), ReportError> {
        if let Some(e) = self.error.take() {
            return Err(e);
        }
        let mut nav = page_head("Report Navigation");
        nav.push_str("<div id=\"content\">\n<h1>Report Navigation</h1>\n<ul class=\"nav\">\n");
        nav.push_str("<li><a href=\"summary.html\" target=\"content\">Case Summary</a></li>\n");
        for p in &self.pages {
            let _ = writeln!(
                nav,
                "<li><a href=\"{}\" target=\"content\">{} ({})</a></li>",
                esc(&p.file),
                esc(&p.title),
                p.rows
            );
        }
        nav.push_str("</ul>\n</div>\n</body>\n</html>");
        self.write_file("nav.html", &nav)?;
        let index = format!(
            "<html>\n<head>\n<title>postmortem Report</title>\n<meta http-equiv=\"Content-Type\" content=\"text/html; charset=utf-8\">\n</head>\n<frameset cols=\"350px,*\">\n<frame src=\"{SUBDIR}/nav.html\" name=\"nav\">\n<frame src=\"{SUBDIR}/summary.html\" name=\"content\">\n<noframes>Your browser is not compatible with our frame setup.<br />\nPlease see <a href=\"{SUBDIR}/nav.html\">the navigation page</a> for artifact links,<br />\nand <a href=\"{SUBDIR}/summary.html\">the summary page</a> for a case summary.</noframes>\n</frameset>\n</html>"
        );
        self.write_file("report.html", &index)
    }

    fn start_data_type(&mut self, title: &str, description: &str) -> Result<(), ReportError> {
        let base = sanitize(title).replace(' ', "_");
        let mut file = format!("{base}.html");
        let mut n = 1;
        while self.pages.iter().any(|p| p.file == file) {
            n += 1;
            file = format!("{base}_{n}.html");
        }
        let path = self.content().join(&file);
        let f = std::fs::File::create(&path).map_err(io_err(&path))?;
        self.out = Some(std::io::BufWriter::new(f));
        self.rows_in_page = 0;
        self.pages.push(Page {
            title: title.to_owned(),
            file,
            rows: 0,
        });
        let mut head = page_head(title);
        let _ = write!(
            head,
            "<div id=\"header\">{}</div>\n<div id=\"content\">\n",
            esc(title)
        );
        if !description.is_empty() {
            let _ = writeln!(head, "<p><strong>{}</strong></p>", esc(description));
        }
        self.w(&head)
    }

    fn end_data_type(&mut self) -> Result<(), ReportError> {
        self.w("</div>\n</body>\n</html>")?;
        if let Some(mut out) = self.out.take() {
            let p = self.dir.clone();
            out.flush().map_err(io_err(&p))?;
        }
        if let Some(p) = self.pages.last_mut() {
            p.rows = self.rows_in_page;
        }
        Ok(())
    }

    fn add_set_index(&mut self, sets: &[String]) -> Result<(), ReportError> {
        let mut s = String::from("<ul>\n");
        for set in sets {
            let _ = writeln!(s, "\t<li><a href=\"#{a}\">{a}</a></li>", a = esc(set));
        }
        s.push_str("</ul>\n");
        self.w(&s)
    }

    fn start_set(&mut self, name: &str) -> Result<(), ReportError> {
        self.w(&format!(
            "<h1><a name=\"{n}\">{n}</a></h1>\n<div class=\"keyword_list\">\n",
            n = esc(name)
        ))
    }

    fn end_set(&mut self) -> Result<(), ReportError> {
        self.w("</div>\n")
    }

    fn add_set_element(&mut self, name: &str) -> Result<(), ReportError> {
        self.w(&format!("<h4>{}</h4>\n", esc(name)))
    }

    fn start_table(&mut self, headers: &[String]) -> Result<(), ReportError> {
        let mut s = String::from("<table>\n<thead>\n\t<tr>\n");
        for h in headers {
            let _ = writeln!(s, "\t\t<th>{}</th>", esc(h));
        }
        s.push_str("\t</tr>\n</thead>\n");
        self.w(&s)
    }

    fn add_row(&mut self, cells: &[String]) -> Result<(), ReportError> {
        let mut s = String::from("\t<tr>\n");
        for c in cells {
            let _ = writeln!(s, "\t\t<td>{}</td>", esc(c));
        }
        s.push_str("\t</tr>\n");
        self.rows_in_page += 1;
        self.w(&s)
    }

    fn end_table(&mut self) -> Result<(), ReportError> {
        self.w("</table>\n")
    }
}

