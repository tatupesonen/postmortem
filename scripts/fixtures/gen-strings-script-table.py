#!/usr/bin/env python3
"""Generates crates/pm-text/src/strings/script_table.rs from Autopsy's
Core/src/org/sleuthkit/autopsy/coreutils/StringExtract.properties.

Autopsy (Apache-2.0) maps every BMP code point to a script ordinal of its
StringExtractUnicodeTable.SCRIPT enum; the table is stored as runs.

Usage: gen-strings-script-table.py <StringExtract.properties> <output.rs>
"""
import re
import sys


def main() -> None:
    src, out = sys.argv[1], sys.argv[2]
    with open(src, encoding="latin-1") as f:
        text = f.read()
    vals = [int(x) for x in re.search(r"UnicodeTable=(.*)", text, re.S).group(1).split()]
    if len(vals) != 65536:
        raise SystemExit(f"expected 65536 entries, got {len(vals)}")
    runs = []
    prev = None
    for cp, v in enumerate(vals):
        if v != prev:
            runs.append((cp, v))
            prev = v
    lines = [
        "//! Generated by `scripts/fixtures/gen-strings-script-table.py` from",
        "//! Autopsy's `StringExtract.properties` (Apache-2.0): the script of every",
        "//! BMP code point, as runs `(first code point, script ordinal)`.",
        "//! Do not edit.",
        "",
        f"pub(super) static RUNS: [(u16, u8); {len(runs)}] = [",
    ]
    for i in range(0, len(runs), 6):
        lines.append(
            "    " + " ".join(f"(0x{cp:04X}, {v})," for cp, v in runs[i : i + 6])
        )
    lines.append("];")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
