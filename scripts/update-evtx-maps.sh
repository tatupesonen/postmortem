#!/usr/bin/env bash
# Bundles EvtxECmd's event log maps (MIT, (c) Eric Zimmerman) into one
# multi-document YAML file embedded by pm-evtlog.
# Usage: scripts/update-evtx-maps.sh [path to a clone of github.com/EricZimmerman/evtx]
set -euo pipefail
src="${1:-$HOME/slop/ez/evtx}"
out="$(dirname "$0")/../crates/pm-evtlog/maps"
mkdir -p "$out"
cp "$src/LICENSE" "$out/LICENSE-EvtxECmd"
rev="$(git -C "$src" rev-parse --short HEAD)"
{
  echo "# EvtxECmd maps from https://github.com/EricZimmerman/evtx (commit $rev),"
  echo "# MIT licence, see LICENSE-EvtxECmd. Generated by scripts/update-evtx-maps.sh."
  for f in "$src"/evtx/Maps/*.map; do
    echo "---"
    echo "# $(basename "$f")"
    # Strip a UTF-8 BOM and CRs; keep the document as is.
    sed -e '1s/^\xEF\xBB\xBF//' -e 's/\r$//' "$f"
  done
} > "$out/evtxecmd.yaml"
echo "wrote $(grep -c '^---$' "$out/evtxecmd.yaml") maps to $out/evtxecmd.yaml"
